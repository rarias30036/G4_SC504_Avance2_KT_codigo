-- ejecutar como admin
SET SERVEROUTPUT ON

-- sinonimos privados para que app y dev no usen el prefijo del esquema
BEGIN
  FOR o IN (SELECT DISTINCT p.TABLE_NAME
              FROM DBA_TAB_PRIVS p
             WHERE p.OWNER = 'FIDE_CS_OWNER'
               AND p.GRANTEE IN ('FIDE_CS_APP_ROL', 'FIDE_CS_CONSULTA_ROL')) LOOP
    EXECUTE IMMEDIATE 'CREATE OR REPLACE SYNONYM FIDE_CS_APP.' || o.TABLE_NAME || ' FOR FIDE_CS_OWNER.' || o.TABLE_NAME;
  END LOOP;
  FOR o IN (SELECT DISTINCT p.TABLE_NAME
              FROM DBA_TAB_PRIVS p
             WHERE p.OWNER = 'FIDE_CS_OWNER'
               AND p.GRANTEE = 'FIDE_CS_DEV') LOOP
    EXECUTE IMMEDIATE 'CREATE OR REPLACE SYNONYM FIDE_CS_DEV.' || o.TABLE_NAME || ' FOR FIDE_CS_OWNER.' || o.TABLE_NAME;
  END LOOP;
  DBMS_OUTPUT.PUT_LINE('sinonimos creados');
END;
/

-- auditoria unificada sobre operaciones sensibles
CREATE AUDIT POLICY FIDE_CS_DML_SENSIBLE_POL
  ACTIONS UPDATE ON FIDE_CS_OWNER.FIDE_USUARIO_TB,
          UPDATE ON FIDE_CS_OWNER.FIDE_SEVERIDAD_TB,
          UPDATE ON FIDE_CS_OWNER.FIDE_INCIDENTE_TB,
          DELETE ON FIDE_CS_OWNER.FIDE_INCIDENTE_TB,
          DELETE ON FIDE_CS_OWNER.FIDE_HISTORIAL_INCIDENTE_TB;

CREATE AUDIT POLICY FIDE_CS_DDL_POL
  ACTIONS CREATE TABLE, ALTER TABLE, DROP TABLE,
          CREATE PROCEDURE, ALTER PROCEDURE, DROP PROCEDURE,
          CREATE TRIGGER, DROP TRIGGER;

CREATE AUDIT POLICY FIDE_CS_SESION_POL
  ACTIONS LOGON, LOGOFF;

AUDIT POLICY FIDE_CS_DML_SENSIBLE_POL;
AUDIT POLICY FIDE_CS_DDL_POL BY FIDE_CS_OWNER, FIDE_CS_DEV;
AUDIT POLICY FIDE_CS_SESION_POL BY FIDE_CS_OWNER, FIDE_CS_DEV, FIDE_CS_APP;

-- verificacion
SELECT owner, synonym_name, table_owner, table_name
FROM dba_synonyms
WHERE owner IN ('FIDE_CS_APP', 'FIDE_CS_DEV')
ORDER BY owner, synonym_name;

SELECT policy_name, enabled_option, entity_name, success, failure
FROM audit_unified_enabled_policies
WHERE policy_name LIKE 'FIDE_CS%'
ORDER BY policy_name;

SELECT grantee, granted_role FROM dba_role_privs WHERE grantee LIKE 'FIDE_CS%' ORDER BY grantee;
