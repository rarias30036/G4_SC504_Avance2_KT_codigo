-- desarrolladores: privilegios directos para compilar pl/sql propio, sin delete ni ddl sobre el esquema duenio
BEGIN
  FOR t IN (SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME LIKE 'FIDE%') LOOP
    EXECUTE IMMEDIATE 'GRANT SELECT, INSERT, UPDATE ON ' || t.TABLE_NAME || ' TO FIDE_CS_DEV';
  END LOOP;
  FOR s IN (SELECT SEQUENCE_NAME FROM USER_SEQUENCES WHERE SEQUENCE_NAME LIKE 'FIDE%') LOOP
    EXECUTE IMMEDIATE 'GRANT SELECT ON ' || s.SEQUENCE_NAME || ' TO FIDE_CS_DEV';
  END LOOP;
  FOR v IN (SELECT VIEW_NAME FROM USER_VIEWS WHERE VIEW_NAME LIKE 'FIDE%') LOOP
    EXECUTE IMMEDIATE 'GRANT SELECT ON ' || v.VIEW_NAME || ' TO FIDE_CS_DEV';
  END LOOP;
  FOR o IN (SELECT OBJECT_NAME FROM USER_OBJECTS
             WHERE OBJECT_TYPE IN ('PROCEDURE', 'FUNCTION', 'PACKAGE') AND OBJECT_NAME LIKE 'FIDE%') LOOP
    EXECUTE IMMEDIATE 'GRANT EXECUTE, DEBUG ON ' || o.OBJECT_NAME || ' TO FIDE_CS_DEV';
  END LOOP;
  DBMS_OUTPUT.PUT_LINE('privilegios otorgados a FIDE_CS_DEV');
END;
/

-- verificacion
SELECT grantee, privilege, COUNT(*) AS objetos
FROM user_tab_privs_made
GROUP BY grantee, privilege
ORDER BY grantee, privilege;
