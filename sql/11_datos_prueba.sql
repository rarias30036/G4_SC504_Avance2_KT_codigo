  FUNCTION activo (p_codigo VARCHAR2) RETURN NUMBER IS
    v NUMBER;
  BEGIN
    SELECT ID_ACTIVO INTO v FROM FIDE_ACTIVO_TB WHERE CODIGO_INVENTARIO = p_codigo;
    RETURN v;
  END;

  FUNCTION tipo (p_nombre VARCHAR2) RETURN NUMBER IS
    v NUMBER;
  BEGIN
    SELECT ID_TIPO_INCIDENTE INTO v FROM FIDE_TIPO_INCIDENTE_TB WHERE NOMBRE_TIPO = p_nombre;
    RETURN v;
  END;

  FUNCTION vuln (p_codigo VARCHAR2, p_cve VARCHAR2) RETURN NUMBER IS
    v NUMBER;
  BEGIN
    SELECT V.ID_VULNERABILIDAD INTO v
      FROM FIDE_VULNERABILIDAD_TB V JOIN FIDE_ACTIVO_TB A ON A.ID_ACTIVO = V.ID_ACTIVO
     WHERE A.CODIGO_INVENTARIO = p_codigo AND V.ID_CVE = p_cve;
    RETURN v;
  END;
