-- rn-04, rn-06, rn-07 y rn-08: control de estados e historial del incidente
CREATE OR REPLACE TRIGGER FIDE_INCIDENTE_ESTADO_TRG
FOR INSERT OR UPDATE ON FIDE_INCIDENTE_TB
COMPOUND TRIGGER

  BEFORE EACH ROW IS
    v_final_actual FIDE_ESTADO_INCIDENTE_TB.ES_FINAL%TYPE;
    v_final_nuevo  FIDE_ESTADO_INCIDENTE_TB.ES_FINAL%TYPE;
  BEGIN
    IF INSERTING THEN
      SELECT ID_ESTADO_INCIDENTE INTO :NEW.ID_ESTADO_INCIDENTE
        FROM FIDE_ESTADO_INCIDENTE_TB WHERE NOMBRE_ESTADO = 'Abierto';
      :NEW.FECHA_REGISTRO := FIDE_AHORA_FN;
      :NEW.FECHA_CIERRE := NULL;
    ELSE
      SELECT ES_FINAL INTO v_final_actual
        FROM FIDE_ESTADO_INCIDENTE_TB WHERE ID_ESTADO_INCIDENTE = :OLD.ID_ESTADO_INCIDENTE;
      IF v_final_actual = 'S' THEN
        RAISE_APPLICATION_ERROR(-20008, 'el incidente ' || :OLD.ID_INCIDENTE || ' esta cerrado y no puede modificarse');
      END IF;

      IF :NEW.ID_ESTADO_INCIDENTE <> :OLD.ID_ESTADO_INCIDENTE THEN
        IF FIDE_VALIDAR_TRANSICION_FN(:OLD.ID_ESTADO_INCIDENTE, :NEW.ID_ESTADO_INCIDENTE) = 'N' THEN
          RAISE_APPLICATION_ERROR(-20006, 'la transicion de estado solicitada no esta permitida');
        END IF;
        SELECT ES_FINAL INTO v_final_nuevo
          FROM FIDE_ESTADO_INCIDENTE_TB WHERE ID_ESTADO_INCIDENTE = :NEW.ID_ESTADO_INCIDENTE;
        IF v_final_nuevo = 'S' THEN
          IF FIDE_CONTAR_CONTROLES_FN(:NEW.ID_INCIDENTE) = 0 THEN
            RAISE_APPLICATION_ERROR(-20009, 'el incidente debe tener al menos un control aplicado para cerrarse');
          END IF;
          :NEW.FECHA_CIERRE := FIDE_AHORA_FN;
        END IF;
      END IF;
    END IF;
  END BEFORE EACH ROW;

  AFTER EACH ROW IS
    v_estado_anterior FIDE_HISTORIAL_INCIDENTE_TB.ID_ESTADO_ANTERIOR%TYPE;
    v_comentario      FIDE_HISTORIAL_INCIDENTE_TB.COMENTARIO%TYPE;
    v_id_usuario      FIDE_HISTORIAL_INCIDENTE_TB.ID_USUARIO%TYPE;
    v_registrar       BOOLEAN := FALSE;
  BEGIN
    IF INSERTING THEN
      v_registrar := TRUE;
      v_estado_anterior := NULL;
      v_comentario := NVL(FIDE_CONTEXTO_PKG.g_comentario, 'registro del incidente');
      v_id_usuario := NVL(FIDE_CONTEXTO_PKG.g_id_usuario, :NEW.ID_USUARIO_REPORTA);
    ELSIF :NEW.ID_ESTADO_INCIDENTE <> :OLD.ID_ESTADO_INCIDENTE THEN
      v_registrar := TRUE;
      v_estado_anterior := :OLD.ID_ESTADO_INCIDENTE;
      v_comentario := NVL(FIDE_CONTEXTO_PKG.g_comentario, 'cambio de estado');
      v_id_usuario := NVL(FIDE_CONTEXTO_PKG.g_id_usuario, NVL(:NEW.ID_USUARIO_ASIGNADO, :NEW.ID_USUARIO_REPORTA));
    END IF;

    IF v_registrar THEN
      INSERT INTO FIDE_HISTORIAL_INCIDENTE_TB (ID_INCIDENTE, ID_ESTADO_ANTERIOR, ID_ESTADO_NUEVO, ID_USUARIO, COMENTARIO)
      VALUES (:NEW.ID_INCIDENTE, v_estado_anterior, :NEW.ID_ESTADO_INCIDENTE, v_id_usuario, v_comentario);
    END IF;
  END AFTER EACH ROW;

END FIDE_INCIDENTE_ESTADO_TRG;
/

-- rn-13: el responsable de un activo debe ser un usuario activo
CREATE OR REPLACE TRIGGER FIDE_ACTIVO_RESPONSABLE_TRG
BEFORE INSERT OR UPDATE OF ID_USUARIO_RESPONSABLE ON FIDE_ACTIVO_TB
FOR EACH ROW
DECLARE
  v_estado FIDE_USUARIO_TB.ID_ESTADO%TYPE;
BEGIN
  SELECT ID_ESTADO INTO v_estado FROM FIDE_USUARIO_TB WHERE ID_USUARIO = :NEW.ID_USUARIO_RESPONSABLE;
  IF v_estado <> 1 THEN
    RAISE_APPLICATION_ERROR(-20022, 'el responsable del activo debe ser un usuario activo');
  END IF;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20022, 'el responsable del activo no existe');
END FIDE_ACTIVO_RESPONSABLE_TRG;
/

-- rn-11 y rn-13: vulnerabilidad nueva inicia pendiente y solo sobre activos activos
CREATE OR REPLACE TRIGGER FIDE_VULNERABILIDAD_NUEVA_TRG
BEFORE INSERT ON FIDE_VULNERABILIDAD_TB
FOR EACH ROW
DECLARE
  v_estado_activo FIDE_ACTIVO_TB.ID_ESTADO%TYPE;
BEGIN
  SELECT ID_ESTADO INTO v_estado_activo FROM FIDE_ACTIVO_TB WHERE ID_ACTIVO = :NEW.ID_ACTIVO;
  IF v_estado_activo <> 1 THEN
    RAISE_APPLICATION_ERROR(-20001, 'no se pueden registrar vulnerabilidades sobre activos inactivos');
  END IF;
  SELECT ID_ESTADO_VULNERABILIDAD INTO :NEW.ID_ESTADO_VULNERABILIDAD
    FROM FIDE_ESTADO_VULNERABILIDAD_TB WHERE NOMBRE_ESTADO = 'Pendiente';
  :NEW.ID_USUARIO_REVISOR := NULL;
  :NEW.FECHA_REVISION := NULL;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20001, 'el activo indicado no existe');
END FIDE_VULNERABILIDAD_NUEVA_TRG;
/

