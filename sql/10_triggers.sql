CREATE OR REPLACE TRIGGER FIDE_ESTADO_AUD_TRG
BEFORE INSERT OR UPDATE OR DELETE ON FIDE_ESTADO_TB
FOR EACH ROW
DECLARE
  v_usuario VARCHAR2(30) := SUBSTR(NVL(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'), USER), 1, 30);
BEGIN
  IF INSERTING THEN
    :NEW.CREADO_POR := v_usuario;
    :NEW.FECHA_CREACION := SYSTIMESTAMP;
    :NEW.MODIFICADO_POR := NULL;
    :NEW.FECHA_MODIFICACION := NULL;
    :NEW.ACCION := 'INSERT';
  ELSIF UPDATING THEN
    :NEW.CREADO_POR := :OLD.CREADO_POR;
    :NEW.FECHA_CREACION := :OLD.FECHA_CREACION;
    :NEW.MODIFICADO_POR := v_usuario;
    :NEW.FECHA_MODIFICACION := SYSTIMESTAMP;
    :NEW.ACCION := 'UPDATE';
  ELSE
    RAISE_APPLICATION_ERROR(-20014, 'no se permite eliminar registros de FIDE_ESTADO_TB, deben inactivarse');
  END IF;
END FIDE_ESTADO_AUD_TRG;
