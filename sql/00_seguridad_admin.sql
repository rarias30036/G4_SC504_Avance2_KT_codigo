-- ejecutar como admin en autonomous database
SET SERVEROUTPUT ON

CREATE PROFILE FIDE_CS_PERFIL_SERVICIO_PF LIMIT
  FAILED_LOGIN_ATTEMPTS 5
  PASSWORD_LOCK_TIME 1/24
  PASSWORD_LIFE_TIME UNLIMITED
  PASSWORD_REUSE_MAX 5
  PASSWORD_REUSE_TIME 365;

CREATE PROFILE FIDE_CS_PERFIL_DEV_PF LIMIT
  FAILED_LOGIN_ATTEMPTS 3
  PASSWORD_LOCK_TIME 1/24
  PASSWORD_LIFE_TIME 90
  PASSWORD_GRACE_TIME 7
  PASSWORD_REUSE_MAX 5
  PASSWORD_REUSE_TIME 365;

-- esquema duenio de tablas y objetos
CREATE USER FIDE_CS_OWNER IDENTIFIED BY "faster@Password123"
  DEFAULT TABLESPACE DATA
  QUOTA UNLIMITED ON DATA
  PROFILE FIDE_CS_PERFIL_SERVICIO_PF;

GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW,
      CREATE PROCEDURE, CREATE TRIGGER, CREATE JOB TO FIDE_CS_OWNER;

-- esquema de desarrolladores
CREATE USER FIDE_CS_DEV IDENTIFIED BY "faster@Password123"
  DEFAULT TABLESPACE DATA
  QUOTA 100M ON DATA
  PROFILE FIDE_CS_PERFIL_DEV_PF;

GRANT CREATE SESSION, CREATE PROCEDURE, CREATE VIEW, CREATE SYNONYM,
      DEBUG CONNECT SESSION TO FIDE_CS_DEV;

-- usuario final de la aplicacion
CREATE USER FIDE_CS_APP IDENTIFIED BY "faster@Password123"
  DEFAULT TABLESPACE DATA
  PROFILE FIDE_CS_PERFIL_SERVICIO_PF;

GRANT CREATE SESSION TO FIDE_CS_APP;

-- roles de objeto
CREATE ROLE FIDE_CS_CONSULTA_ROL;
CREATE ROLE FIDE_CS_APP_ROL;

GRANT FIDE_CS_CONSULTA_ROL TO FIDE_CS_APP_ROL;
GRANT FIDE_CS_APP_ROL TO FIDE_CS_APP;
GRANT FIDE_CS_CONSULTA_ROL TO FIDE_CS_DEV;

ALTER USER FIDE_CS_APP DEFAULT ROLE ALL;
ALTER USER FIDE_CS_DEV DEFAULT ROLE ALL;

-- verificacion
SELECT username, account_status, default_tablespace, profile
FROM dba_users
WHERE username LIKE 'FIDE_CS%'
ORDER BY username;

SELECT grantee, privilege FROM dba_sys_privs
WHERE grantee LIKE 'FIDE_CS%'
ORDER BY grantee, privilege;
