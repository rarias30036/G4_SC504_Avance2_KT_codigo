CREATE OR REPLACE VIEW FIDE_USUARIOS_V AS
SELECT U.ID_USUARIO,
       U.NOMBRE_USUARIO,
       U.CEDULA,
       U.NOMBRE,
       U.PRIMER_APELLIDO,
       U.SEGUNDO_APELLIDO,
       U.NOMBRE || ' ' || U.PRIMER_APELLIDO || NVL2(U.SEGUNDO_APELLIDO, ' ' || U.SEGUNDO_APELLIDO, NULL) AS NOMBRE_COMPLETO,
       U.CORREO,
       U.ID_ROL,
       R.NOMBRE_ROL,
       U.ID_DEPARTAMENTO,
       D.NOMBRE_DEPARTAMENTO,
       U.CAPACIDAD_MAXIMA,
       U.ID_ESTADO,
       E.NOMBRE_ESTADO
  FROM FIDE_USUARIO_TB U
  JOIN FIDE_ROL_TB R ON R.ID_ROL = U.ID_ROL
  JOIN FIDE_DEPARTAMENTO_TB D ON D.ID_DEPARTAMENTO = U.ID_DEPARTAMENTO
  JOIN FIDE_ESTADO_TB E ON E.ID_ESTADO = U.ID_ESTADO;

CREATE OR REPLACE VIEW FIDE_CLIENTES_V AS
SELECT C.ID_CLIENTE,
       C.CEDULA_JURIDICA,
       C.RAZON_SOCIAL,
       C.SECTOR,
       C.CORREO_CONTACTO,
       C.TELEFONO,
       C.ID_ESTADO,
       E.NOMBRE_ESTADO,
       (SELECT COUNT(*) FROM FIDE_ACTIVO_TB A WHERE A.ID_CLIENTE = C.ID_CLIENTE AND A.ID_ESTADO = 1) AS ACTIVOS_ACTIVOS
  FROM FIDE_CLIENTE_TB C
  JOIN FIDE_ESTADO_TB E ON E.ID_ESTADO = C.ID_ESTADO;

CREATE OR REPLACE VIEW FIDE_ACTIVOS_V AS
SELECT A.ID_ACTIVO,
       A.CODIGO_INVENTARIO,
       A.NOMBRE_ACTIVO,
       A.ID_CLIENTE,
       C.RAZON_SOCIAL AS CLIENTE,
       A.ID_TIPO_ACTIVO,
       T.NOMBRE_TIPO AS TIPO_ACTIVO,
       A.ID_USUARIO_RESPONSABLE,
       U.NOMBRE || ' ' || U.PRIMER_APELLIDO AS RESPONSABLE,
       A.DIRECCION_IP,
       A.SISTEMA_OPERATIVO,
       A.UBICACION,
       A.FECHA_INGRESO,
       A.ID_ESTADO,
       E.NOMBRE_ESTADO,
       (SELECT COUNT(*)
          FROM FIDE_VULNERABILIDAD_TB V
          JOIN FIDE_ESTADO_VULNERABILIDAD_TB EV ON EV.ID_ESTADO_VULNERABILIDAD = V.ID_ESTADO_VULNERABILIDAD
         WHERE V.ID_ACTIVO = A.ID_ACTIVO
           AND EV.NOMBRE_ESTADO NOT IN ('Mitigada', 'Falso positivo')) AS VULNERABILIDADES_ABIERTAS
  FROM FIDE_ACTIVO_TB A
  JOIN FIDE_CLIENTE_TB C ON C.ID_CLIENTE = A.ID_CLIENTE
  JOIN FIDE_TIPO_ACTIVO_TB T ON T.ID_TIPO_ACTIVO = A.ID_TIPO_ACTIVO
  JOIN FIDE_USUARIO_TB U ON U.ID_USUARIO = A.ID_USUARIO_RESPONSABLE
  JOIN FIDE_ESTADO_TB E ON E.ID_ESTADO = A.ID_ESTADO;

CREATE OR REPLACE VIEW FIDE_CVE_V AS
SELECT C.ID_CVE,
       C.DESCRIPCION,
       C.PUNTAJE_CVSS,
       C.VECTOR_CVSS,
       C.VERSION_CVSS,
       C.FECHA_PUBLICACION,
       S.NOMBRE_SEVERIDAD
  FROM FIDE_CVE_TB C
  JOIN FIDE_SEVERIDAD_TB S ON S.ID_SEVERIDAD = FIDE_CALCULAR_SEVERIDAD_FN(C.PUNTAJE_CVSS);

CREATE OR REPLACE VIEW FIDE_VULNERABILIDADES_V AS
SELECT V.ID_VULNERABILIDAD,
       V.ID_ACTIVO,
       A.CODIGO_INVENTARIO,
       A.NOMBRE_ACTIVO,
       CL.RAZON_SOCIAL AS CLIENTE,
       V.ID_CVE,
       C.PUNTAJE_CVSS,
       S.NOMBRE_SEVERIDAD,
       V.ID_ESTADO_VULNERABILIDAD,
       EV.NOMBRE_ESTADO,
       V.ID_USUARIO_REVISOR,
       U.NOMBRE || ' ' || U.PRIMER_APELLIDO AS REVISOR,
       V.FECHA_DETECCION,
       V.FECHA_REVISION,
       V.OBSERVACIONES
  FROM FIDE_VULNERABILIDAD_TB V
  JOIN FIDE_ACTIVO_TB A ON A.ID_ACTIVO = V.ID_ACTIVO
  JOIN FIDE_CLIENTE_TB CL ON CL.ID_CLIENTE = A.ID_CLIENTE
  JOIN FIDE_CVE_TB C ON C.ID_CVE = V.ID_CVE
  JOIN FIDE_SEVERIDAD_TB S ON S.ID_SEVERIDAD = FIDE_CALCULAR_SEVERIDAD_FN(C.PUNTAJE_CVSS)
  JOIN FIDE_ESTADO_VULNERABILIDAD_TB EV ON EV.ID_ESTADO_VULNERABILIDAD = V.ID_ESTADO_VULNERABILIDAD
  LEFT JOIN FIDE_USUARIO_TB U ON U.ID_USUARIO = V.ID_USUARIO_REVISOR;

CREATE OR REPLACE VIEW FIDE_INCIDENTES_DETALLE_V AS
SELECT I.ID_INCIDENTE,
       I.TITULO,
       I.DESCRIPCION,
       I.ID_ACTIVO,
       A.NOMBRE_ACTIVO,
       CL.RAZON_SOCIAL AS CLIENTE,
       I.ID_VULNERABILIDAD,
       V.ID_CVE,
       I.ID_TIPO_INCIDENTE,
       T.NOMBRE_TIPO AS TIPO_INCIDENTE,
       I.ID_SEVERIDAD,
       S.NOMBRE_SEVERIDAD,
       I.ID_ESTADO_INCIDENTE,
       E.NOMBRE_ESTADO,
       I.ID_USUARIO_REPORTA,
       UR.NOMBRE || ' ' || UR.PRIMER_APELLIDO AS REPORTADO_POR,
       I.ID_USUARIO_ASIGNADO,
       UA.NOMBRE || ' ' || UA.PRIMER_APELLIDO AS ASIGNADO_A,
       I.FECHA_DETECCION,
       I.FECHA_REGISTRO,
       I.FECHA_CIERRE,
       I.FECHA_REGISTRO + NUMTODSINTERVAL(S.HORAS_RESPUESTA, 'HOUR') AS LIMITE_RESPUESTA,
       I.FECHA_REGISTRO + NUMTODSINTERVAL(S.HORAS_RESOLUCION, 'HOUR') AS LIMITE_RESOLUCION,
       FIDE_ESTADO_SLA_FN(I.ID_INCIDENTE) AS ESTADO_SLA,
       FIDE_CONTAR_CONTROLES_FN(I.ID_INCIDENTE) AS CONTROLES_APLICADOS
  FROM FIDE_INCIDENTE_TB I
  JOIN FIDE_ACTIVO_TB A ON A.ID_ACTIVO = I.ID_ACTIVO
  JOIN FIDE_CLIENTE_TB CL ON CL.ID_CLIENTE = A.ID_CLIENTE
  JOIN FIDE_TIPO_INCIDENTE_TB T ON T.ID_TIPO_INCIDENTE = I.ID_TIPO_INCIDENTE
  JOIN FIDE_SEVERIDAD_TB S ON S.ID_SEVERIDAD = I.ID_SEVERIDAD
  JOIN FIDE_ESTADO_INCIDENTE_TB E ON E.ID_ESTADO_INCIDENTE = I.ID_ESTADO_INCIDENTE
  JOIN FIDE_USUARIO_TB UR ON UR.ID_USUARIO = I.ID_USUARIO_REPORTA
  LEFT JOIN FIDE_USUARIO_TB UA ON UA.ID_USUARIO = I.ID_USUARIO_ASIGNADO
  LEFT JOIN FIDE_VULNERABILIDAD_TB V ON V.ID_VULNERABILIDAD = I.ID_VULNERABILIDAD;

CREATE OR REPLACE VIEW FIDE_HISTORIAL_INCIDENTE_V AS
SELECT H.ID_HISTORIAL,
       H.ID_INCIDENTE,
       EA.NOMBRE_ESTADO AS ESTADO_ANTERIOR,
       EN.NOMBRE_ESTADO AS ESTADO_NUEVO,
       H.ID_USUARIO,
       U.NOMBRE || ' ' || U.PRIMER_APELLIDO AS USUARIO,
       H.FECHA_CAMBIO,
       H.COMENTARIO
  FROM FIDE_HISTORIAL_INCIDENTE_TB H
  LEFT JOIN FIDE_ESTADO_INCIDENTE_TB EA ON EA.ID_ESTADO_INCIDENTE = H.ID_ESTADO_ANTERIOR
  JOIN FIDE_ESTADO_INCIDENTE_TB EN ON EN.ID_ESTADO_INCIDENTE = H.ID_ESTADO_NUEVO
  JOIN FIDE_USUARIO_TB U ON U.ID_USUARIO = H.ID_USUARIO;

CREATE OR REPLACE VIEW FIDE_ALERTAS_V AS
SELECT AL.ID_ALERTA,
       AL.ID_INCIDENTE,
       I.TITULO,
       S.NOMBRE_SEVERIDAD,
       AL.ID_USUARIO_DESTINO,
       U.NOMBRE || ' ' || U.PRIMER_APELLIDO AS DESTINATARIO,
       AL.TIPO_SLA,
       AL.NIVEL_ESCALAMIENTO,
       AL.FECHA_ALERTA,
       AL.MENSAJE,
       AL.ATENDIDA
  FROM FIDE_ALERTA_ESCALAMIENTO_TB AL
  JOIN FIDE_INCIDENTE_TB I ON I.ID_INCIDENTE = AL.ID_INCIDENTE
  JOIN FIDE_SEVERIDAD_TB S ON S.ID_SEVERIDAD = I.ID_SEVERIDAD
  JOIN FIDE_USUARIO_TB U ON U.ID_USUARIO = AL.ID_USUARIO_DESTINO;

CREATE OR REPLACE VIEW FIDE_CARGA_ANALISTAS_V AS
SELECT U.ID_USUARIO,
       U.NOMBRE || ' ' || U.PRIMER_APELLIDO AS ANALISTA,
       U.CAPACIDAD_MAXIMA,
       FIDE_CARGA_ANALISTA_FN(U.ID_USUARIO) AS CARGA_ACTUAL,
       U.CAPACIDAD_MAXIMA - FIDE_CARGA_ANALISTA_FN(U.ID_USUARIO) AS CUPOS_DISPONIBLES
  FROM FIDE_USUARIO_TB U
  JOIN FIDE_ROL_TB R ON R.ID_ROL = U.ID_ROL
 WHERE R.NOMBRE_ROL = 'Analista'
   AND U.ID_ESTADO = 1;

CREATE OR REPLACE VIEW FIDE_CONTROLES_V AS
SELECT C.ID_CONTROL,
       C.CODIGO_CONTROL,
       C.NOMBRE_CONTROL,
       C.TIPO_CONTROL,
       C.ID_POLITICA,
       P.NOMBRE_POLITICA,
       P.VERSION,
       C.ID_ESTADO,
       E.NOMBRE_ESTADO
  FROM FIDE_CONTROL_TB C
  JOIN FIDE_POLITICA_TB P ON P.ID_POLITICA = C.ID_POLITICA
  JOIN FIDE_ESTADO_TB E ON E.ID_ESTADO = C.ID_ESTADO;

CREATE OR REPLACE VIEW FIDE_INCIDENTE_CONTROLES_V AS
SELECT IC.ID_INCIDENTE,
       IC.ID_CONTROL,
       C.CODIGO_CONTROL,
       C.NOMBRE_CONTROL,
       C.TIPO_CONTROL,
       IC.ID_USUARIO,
       U.NOMBRE || ' ' || U.PRIMER_APELLIDO AS APLICADO_POR,
       IC.FECHA_APLICACION,
       IC.RESULTADO
  FROM FIDE_INCIDENTE_CONTROL_TB IC
  JOIN FIDE_CONTROL_TB C ON C.ID_CONTROL = IC.ID_CONTROL
  JOIN FIDE_USUARIO_TB U ON U.ID_USUARIO = IC.ID_USUARIO;

-- catalogos activos para listas desplegables
CREATE OR REPLACE VIEW FIDE_CATALOGOS_V AS
SELECT 'ROL' AS CATALOGO, ID_ROL AS ID, NOMBRE_ROL AS NOMBRE FROM FIDE_ROL_TB WHERE ID_ESTADO = 1
UNION ALL
SELECT 'DEPARTAMENTO', ID_DEPARTAMENTO, NOMBRE_DEPARTAMENTO FROM FIDE_DEPARTAMENTO_TB WHERE ID_ESTADO = 1
UNION ALL
SELECT 'TIPO_ACTIVO', ID_TIPO_ACTIVO, NOMBRE_TIPO FROM FIDE_TIPO_ACTIVO_TB WHERE ID_ESTADO = 1
UNION ALL
SELECT 'TIPO_INCIDENTE', ID_TIPO_INCIDENTE, NOMBRE_TIPO FROM FIDE_TIPO_INCIDENTE_TB WHERE ID_ESTADO = 1
UNION ALL
SELECT 'SEVERIDAD', ID_SEVERIDAD, NOMBRE_SEVERIDAD FROM FIDE_SEVERIDAD_TB WHERE ID_ESTADO = 1
UNION ALL
SELECT 'ESTADO_INCIDENTE', ID_ESTADO_INCIDENTE, NOMBRE_ESTADO FROM FIDE_ESTADO_INCIDENTE_TB
UNION ALL
SELECT 'ESTADO_VULNERABILIDAD', ID_ESTADO_VULNERABILIDAD, NOMBRE_ESTADO FROM FIDE_ESTADO_VULNERABILIDAD_TB
UNION ALL
SELECT 'POLITICA', ID_POLITICA, NOMBRE_POLITICA FROM FIDE_POLITICA_TB WHERE ID_ESTADO = 1;

-- rf-16: incidentes por estado y severidad
CREATE OR REPLACE VIEW FIDE_REPORTE_INCIDENTES_V AS
SELECT E.NOMBRE_ESTADO,
       S.NOMBRE_SEVERIDAD,
       COUNT(I.ID_INCIDENTE) AS TOTAL
  FROM FIDE_ESTADO_INCIDENTE_TB E
 CROSS JOIN FIDE_SEVERIDAD_TB S
  LEFT JOIN FIDE_INCIDENTE_TB I
    ON I.ID_ESTADO_INCIDENTE = E.ID_ESTADO_INCIDENTE
   AND I.ID_SEVERIDAD = S.ID_SEVERIDAD
 GROUP BY E.NOMBRE_ESTADO, E.ORDEN, S.NOMBRE_SEVERIDAD, S.CVSS_MINIMO;

-- rf-16: vulnerabilidades por activo
CREATE OR REPLACE VIEW FIDE_REPORTE_VULN_ACTIVO_V AS
SELECT A.ID_ACTIVO,
       A.CODIGO_INVENTARIO,
       A.NOMBRE_ACTIVO,
       CL.RAZON_SOCIAL AS CLIENTE,
       COUNT(V.ID_VULNERABILIDAD) AS TOTAL_VULNERABILIDADES,
       SUM(CASE WHEN EV.NOMBRE_ESTADO NOT IN ('Mitigada', 'Falso positivo') THEN 1 ELSE 0 END) AS ABIERTAS,
       MAX(C.PUNTAJE_CVSS) AS CVSS_MAXIMO
  FROM FIDE_ACTIVO_TB A
  JOIN FIDE_CLIENTE_TB CL ON CL.ID_CLIENTE = A.ID_CLIENTE
  LEFT JOIN FIDE_VULNERABILIDAD_TB V ON V.ID_ACTIVO = A.ID_ACTIVO
  LEFT JOIN FIDE_CVE_TB C ON C.ID_CVE = V.ID_CVE
  LEFT JOIN FIDE_ESTADO_VULNERABILIDAD_TB EV ON EV.ID_ESTADO_VULNERABILIDAD = V.ID_ESTADO_VULNERABILIDAD
 GROUP BY A.ID_ACTIVO, A.CODIGO_INVENTARIO, A.NOMBRE_ACTIVO, CL.RAZON_SOCIAL;

